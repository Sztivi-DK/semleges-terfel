	<p>A Semleges Térfél nem csak egy oldal – egy gondolkodásmód. Itt nem a szenzációhajhászás, hanem a hiteles tartalom számít. A magyar labdarúgás eseményeit kiegyensúlyozottan, nagy szenvedéllyel mutatjuk be.
	</p>
	<p>A Semleges Térfél célja, hogy hidat építsen szurkolók, szakértők és kíváncsi olvasók között – mert a magyar futball jövője közös ügyünk.
	</p>
    </section>
