	</p>
	<p>Műsorainkban kötetlenül beszéljük ki az aktuális meccseket, vlogokban osztjuk meg a véleményünket a magyar labdarúgás eseményeiről, és külön futballtörténeti sorozatunk is van Magyar Futball Históriák néven, ahol bemutatjuk a hazai foci legendás pillanatait.  Rivális csapatok szurkolói vagyunk, de közös a szenvedélyünk: a Magyar Foci . Itt őszinte vélemények és szenvedélyes beszélgetések várnak – minden finomkodás nélkül!
	</p>	
